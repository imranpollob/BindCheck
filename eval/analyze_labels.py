"""Analyze returned rater labels (sets H and D) per AMENDMENT-ADJUDICATION-SAMPLE.md.

Precision per stratum = TP / (TP + FP), Wilson 95% intervals; `unclear` is
reported separately and never counted. Per-tool estimate is population-weighted
over strata. Agreement: raw agreement and Cohen's kappa (3-way and on cards both
raters decided). Disagreements are listed for resolution; they get no label here.
"""
from __future__ import annotations

import csv
import json
import math
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LAB = ROOT / "review/labels"
MANIFEST = ROOT / "review/heldout-sample/sample-manifest.json"
UNBLIND = ROOT / "reports/heldout/warning-unblind-key.csv"
DEV_KEY = ROOT / "reports/groundtruth/warning-blind-key.csv"
OUT = ROOT / "reports/labels"
VALID = {"TP", "FP", "unclear"}


def load(path: Path) -> dict[str, dict]:
    rows = list(csv.DictReader(path.open(encoding="utf-8-sig")))
    out = {}
    for r in rows:
        wid = r["warning_id"].strip()
        if wid in out:
            sys.exit(f"duplicate {wid} in {path}")
        lab = r["label"].strip()
        norm = {"tp": "TP", "fp": "FP", "unclear": "unclear"}.get(lab.lower())
        if norm is None:
            sys.exit(f"invalid label {lab!r} for {wid} in {path}")
        out[wid] = {"label": norm, "reason": r.get("rater_reason", "").strip()}
    return out


def wilson(k: int, n: int, z: float = 1.959964) -> tuple[float, float]:
    if n == 0:
        return (float("nan"), float("nan"))
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return (max(0.0, c - h), min(1.0, c + h))


def kappa(a: list[str], b: list[str]) -> float:
    n = len(a)
    if n == 0:
        return float("nan")
    po = sum(x == y for x, y in zip(a, b)) / n
    ca, cb = Counter(a), Counter(b)
    pe = sum(ca[k] * cb[k] for k in set(ca) | set(cb)) / (n * n)
    return float("nan") if pe == 1 else (po - pe) / (1 - pe)


def stratum(row: dict) -> tuple[str, str]:
    if row["tool"] == "arm-c":
        return ("arm-c", row["reason_code"])
    if row["pattern"] == "P4":
        return ("bindcheck-zk", f"P4/{row['reason_code']}")
    return ("bindcheck-zk", row["pattern"])


def fmt(k: int, n: int) -> str:
    if n == 0:
        return "–"
    lo, hi = wilson(k, n)
    return f"{k}/{n} = {k/n:.2f} [{lo:.2f}, {hi:.2f}]"


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    man = json.loads(MANIFEST.read_text())
    ids = man["card_ids"]
    key = {r["card_id"]: r for r in csv.DictReader(UNBLIND.open())}
    pop = {(s["tool"], s["stratum"]): s["population"] for s in man["strata"]}
    dev = {r["warning_id"]: r for r in csv.DictReader(DEV_KEY.open())}

    H = {r: load(LAB / f"rater-{r}/LABELS-set-H-rater-{r}.csv") for r in "AB"}
    D = {r: load(LAB / f"rater-{r}/LABELS-set-D-rater-{r}.csv") for r in "AB"}
    for r in "AB":
        if set(H[r]) != set(ids):
            sys.exit(f"set H rater {r}: ids differ from manifest "
                     f"(missing {sorted(set(ids)-set(H[r]))}, extra {sorted(set(H[r])-set(ids))})")
        if set(D[r]) != set(dev):
            sys.exit(f"set D rater {r}: ids differ from DEV key")

    lines = ["# Label analysis (sets H and D)", "",
             "Generated by `eval/analyze_labels.py` from the sealed sheets in `review/labels/` "
             "(see `review/labels/SEAL.md`). Precision = TP/(TP+FP), Wilson 95% intervals; "
             "`unclear` is reported separately and never counted.", ""]

    # ---------- set H ----------
    per = defaultdict(list)
    ledger = []
    for wid in ids:
        st = stratum(key[wid])
        a, b = H["A"][wid]["label"], H["B"][wid]["label"]
        per[st].append((wid, a, b))
        ledger.append({"warning_id": wid, "tool": st[0], "stratum": st[1],
                       "repository": key[wid]["repository"], "source_path": key[wid]["source_path"],
                       "source_line": key[wid]["source_line"], "rater_A": a, "rater_B": b,
                       "agree": a == b, "reason_A": H["A"][wid]["reason"], "reason_B": H["B"][wid]["reason"]})

    la = [H["A"][w]["label"] for w in ids]
    lb = [H["B"][w]["label"] for w in ids]
    both = [(x, y) for x, y in zip(la, lb) if x != "unclear" and y != "unclear"]
    lines += ["## Set H — 100 held-out sample cards", "",
              f"- Raw agreement: {sum(x == y for x, y in zip(la, lb))}/100; "
              f"Cohen's κ (3 labels) = {kappa(la, lb):.3f}",
              f"- Cards both raters decided (TP/FP): {len(both)}; agreement "
              f"{sum(x == y for x, y in both)}/{len(both)}; κ = {kappa(*map(list, zip(*both))) if both else float('nan'):.3f}",
              f"- Label counts — A: {dict(Counter(la))}; B: {dict(Counter(lb))}", "",
              "### Precision per stratum", "",
              "| Tool | Stratum | Pop. | n | Rater A | Rater B | Both agree TP / agreed decided | Disagree | Unclear (A/B) |",
              "| --- | --- | ---: | ---: | --- | --- | --- | ---: | --- |"]
    summary = {"set_H": {"strata": {}}, "set_D": {}}
    tool_est = defaultdict(lambda: defaultdict(float))
    for st in sorted(per):
        rows = per[st]
        def prec(idx):
            labs = [r[idx] for r in rows]
            return labs.count("TP"), labs.count("TP") + labs.count("FP"), labs.count("unclear")
        ka, na, ua = prec(1)
        kb, nb, ub = prec(2)
        agreed = [r[1] for r in rows if r[1] == r[2] and r[1] != "unclear"]
        kc, nc = agreed.count("TP"), len(agreed)
        dis = sum(1 for r in rows if r[1] != r[2])
        lines.append(f"| {st[0]} | {st[1]} | {pop[st]} | {len(rows)} | {fmt(ka, na)} | {fmt(kb, nb)} | "
                     f"{fmt(kc, nc)} | {dis} | {ua}/{ub} |")
        summary["set_H"]["strata"][f"{st[0]}:{st[1]}"] = {
            "population": pop[st], "n": len(rows), "A": [ka, na, ua], "B": [kb, nb, ub],
            "agreed": [kc, nc], "disagree": dis}
        for name, k, n in (("A", ka, na), ("B", kb, nb), ("agreed", kc, nc)):
            if n:
                tool_est[(st[0], name)]["w"] += pop[st]
                tool_est[(st[0], name)]["wp"] += pop[st] * k / n

    lines += ["", "### Population-weighted precision per tool", "",
              "Weights are stratum populations; strata with no decided card are dropped from both numerator and denominator "
              "(P4 duplicate-IC, population 1, was not sampled).", "",
              "| Tool | Rater A | Rater B | Agreed cards only |", "| --- | --- | --- | --- |"]
    for tool in ("bindcheck-zk", "arm-c"):
        cells = []
        for name in ("A", "B", "agreed"):
            e = tool_est[(tool, name)]
            cells.append(f"{e['wp']/e['w']:.2f} (weight {int(e['w'])})" if e["w"] else "–")
            summary["set_H"].setdefault("weighted", {})[f"{tool}:{name}"] = e["wp"] / e["w"] if e["w"] else None
        lines.append(f"| {tool} | " + " | ".join(cells) + " |")

    dis_rows = [r for r in ledger if not r["agree"]]
    lines += ["", f"### Disagreements to resolve ({len(dis_rows)})", "",
              "| Card | Stratum | A | B |", "| --- | --- | --- | --- |"]
    for r in dis_rows:
        lines.append(f"| {r['warning_id']} | {r['tool']}:{r['stratum']} | {r['rater_A']} | {r['rater_B']} |")

    # ---------- set D ----------
    dids = sorted(dev)
    da = [D["A"][w]["label"] for w in dids]
    db = [D["B"][w]["label"] for w in dids]
    auth = [{"true positive": "TP", "false positive": "FP"}.get(dev[w]["author_adjudication"], "unclear") for w in dids]
    lines += ["", "## Set D — 16 DEV gate cards", "",
              f"- Rater agreement {sum(x == y for x, y in zip(da, db))}/16; κ = {kappa(da, db):.3f}",
              f"- Label counts — A: {dict(Counter(da))}; B: {dict(Counter(db))}; author pre-adjudication: {dict(Counter(auth))}",
              f"- Agreement with author pre-adjudication — A: {sum(x == y for x, y in zip(da, auth))}/16; "
              f"B: {sum(x == y for x, y in zip(db, auth))}/16", "",
              "| Card | DEV row | Pattern | Author | A | B |", "| --- | --- | --- | --- | --- | --- |"]
    for w, x, y, z in zip(dids, da, db, auth):
        lines.append(f"| {w} | {dev[w]['row']} | {dev[w]['pattern']} | {z} | {x} | {y} |")
    summary["set_D"] = {"A": dict(Counter(da)), "B": dict(Counter(db)), "author": dict(Counter(auth)),
                        "agree_AB": sum(x == y for x, y in zip(da, db)), "kappa": kappa(da, db)}

    (OUT / "LABEL-ANALYSIS.md").write_text("\n".join(lines) + "\n")
    (OUT / "label-summary.json").write_text(json.dumps(summary, indent=2) + "\n")
    with (OUT / "set-H-ledger.csv").open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(ledger[0]))
        w.writeheader()
        w.writerows(ledger)
    print("\n".join(lines))


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""RV11: cross-tabulate the AI-proposed SoK (Chaliasos et al., USENIX Sec 2024) categories in
RV11-sok-map.csv against patterns P1-P5. Prints Markdown pasted into RV11-SOK-MAP.md.

Usage: python3 -I /home/pollmix/Coding/bc/BindCheck/dataset/labels-v1/analysis/rv11_crosstab.py
"""
import collections as C, csv, hashlib, math, pathlib

HERE = pathlib.Path(__file__).resolve().parents[1]
MAP = HERE / "RV11-sok-map.csv"
LABELS = HERE / "LABELS-v1.csv"
LAYER = {**{f"V{i}": "circuit" for i in (1, 2, 3)}, **{f"V{i}": "integration" for i in (4, 5, 6, 7)},
         "V8": "frontend", "V9": "frontend", "V10": "backend", "V11": "backend", "V12": "backend", "NONE": "none"}
CATS = ["V1", "V4", "V5", "V6", "V7", "V12", "NONE"]
PATS = ["P1", "P2", "P3", "P4", "P5", "OTHER"]
LAYERS = ["integration", "circuit", "backend", "frontend", "none"]


def wilson(k, n, z=1.959964):
    p = k / n; d = 1 + z * z / n; c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return p, max(0.0, c - h), min(1.0, c + h)


def main():
    rows = list(csv.DictReader(open(MAP)))
    lab = {r["item_id"]: r for r in csv.DictReader(open(LABELS))}
    for r in rows:
        l = lab[r["item_id"]]
        assert l["binding"] == "Y" and not l["dup_of"] and l["pattern"] == r["pattern"]
        assert r["sok_category"] in CATS, r
    core = [r for r in rows if r["core"] == "Y"]
    assert len(rows) == 103 and len(core) == 87
    out = ["<!-- generated by analysis/rv11_crosstab.py; do not hand-edit this block -->",
           f"- Input: `RV11-sok-map.csv` sha256 `{hashlib.sha256(MAP.read_bytes()).hexdigest()}`", ""]
    for name, rs in (("All binding", rows), ("Core (PSS != Y)", core)):
        t = C.Counter((r["sok_category"], r["pattern"]) for r in rs)
        out += [f"#### {name}: SoK category x pattern (n = {len(rs)}; cell = all / DIRECT)", "",
                "| SoK category | " + " | ".join(PATS) + " | total | DIRECT |", "|---" * (len(PATS) + 3) + "|"]
        td = C.Counter((r["sok_category"], r["pattern"]) for r in rs if r["sok_fit"] == "DIRECT")
        for c in CATS:
            n = sum(t[(c, p)] for p in PATS); nd = sum(td[(c, p)] for p in PATS)
            out.append(f"| {c} ({LAYER[c]}) | " + " | ".join(f"{t[(c,p)]}/{td[(c,p)]}" for p in PATS) + f" | {n} | {nd} |")
        out.append("| total | " + " | ".join(str(sum(t[(c, p)] for c in CATS)) for p in PATS) + f" | {len(rs)} | {sum(td.values())} |")
        out.append("")
        out += [f"#### {name}: by SoK layer", "", "| SoK layer | any fit | DIRECT fit | LAYER-ONLY |", "|---|---|---|---|"]
        for Lr in LAYERS:
            a = [r for r in rs if LAYER[r["sok_category"]] == Lr]
            d = sum(r["sok_fit"] == "DIRECT" for r in a)
            p, lo, hi = wilson(len(a), len(rs))
            out.append(f"| {Lr} | {len(a)} ({100*p:.0f}% [{100*lo:.0f}, {100*hi:.0f}]) | {d} | {len(a) - d} |")
        nd = sum(r["sok_fit"] != "DIRECT" for r in rs)
        out.append(f"| **no DIRECT category** (LAYER-ONLY + NONE) | {nd} ({100*nd/len(rs):.0f}%) | | |")
        out.append("")
    out += ["#### Per pattern (all 103): share mapped DIRECT, and where", "", "| pattern | n | DIRECT | DIRECT share | integration (any fit) | covered? (DIRECT >= 50%) |", "|---|---|---|---|---|---|"]
    for p in PATS:
        a = [r for r in rows if r["pattern"] == p]
        d = sum(r["sok_fit"] == "DIRECT" for r in a)
        i = sum(LAYER[r["sok_category"]] == "integration" for r in a)
        out.append(f"| {p} | {len(a)} | {d} | {100*d/len(a):.0f}% | {i} | {'yes' if d >= len(a)/2 else '**no**'} |")
    print("\n".join(out))


if __name__ == "__main__":
    main()

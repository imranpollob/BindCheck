#!/usr/bin/env python3
"""D3: cross-tabulate the AI-proposed layer tags (D3-layers.csv) by pattern, severity and tier,
and draw a seeded, tag-stratified spot-check sample of 15 items for the author.

Usage: python3 -I /home/pollmix/Coding/bc/BindCheck/dataset/labels-v1/analysis/d3_crosstab.py
Prints Markdown (pasted into D3-LAYERS.md section 2). Stdlib only.
"""
import collections as C, csv, hashlib, pathlib, random

HERE = pathlib.Path(__file__).resolve().parents[1]
TAGS = HERE / "D3-layers.csv"
LABELS = HERE / "LABELS-v1.csv"
SEED = 20261125
NSPOT = 15
LAYERS = ["CONTRACT-ONLY", "CIRCUIT-ONLY", "BOTH", "VERIFIER/OFFCHAIN"]
PATS = ["P1", "P2", "P3", "P4", "P5", "OTHER"]
SEVS = ["Critical", "High", "Medium", "Low", "Info", "Unrated"]


def sev(s):  # identical to characterize.py
    s = s.lower()
    for k, v in (("crit", "Critical"), ("high", "High"), ("med", "Medium"), ("low", "Low"), ("info", "Info"), ("warn", "Info"), ("note", "Info")):
        if k in s:
            return v
    return "Unrated"


def xtab(rows, key, cols, title, out):
    t = C.Counter((r["layer_tag"], key(r)) for r in rows)
    out += [f"#### {title} (n = {len(rows)})", "", "| layer | " + " | ".join(cols) + " | total | % |", "|---" * (len(cols) + 3) + "|"]
    for L in LAYERS:
        n = sum(t[(L, c)] for c in cols)
        out.append(f"| {L} | " + " | ".join(str(t[(L, c)]) for c in cols) + f" | {n} | {100 * n / len(rows):.0f}% |")
    out.append("| total | " + " | ".join(str(sum(t[(L, c)] for L in LAYERS)) for c in cols) + f" | {len(rows)} | |")
    out.append("")


def main():
    rows = list(csv.DictReader(open(TAGS)))
    lab = {r["item_id"]: r for r in csv.DictReader(open(LABELS))}
    for r in rows:  # join check against frozen labels
        l = lab[r["item_id"]]
        assert l["binding"] == "Y" and not l["dup_of"] and l["pattern"] == r["pattern"] and l["proof_system_soundness"] == r["pss"]
        assert r["layer_tag"] in LAYERS, r
    core = [r for r in rows if r["core"] == "Y"]
    assert len(rows) == 103 and len(core) == 87
    out = ["<!-- generated by analysis/d3_crosstab.py; do not hand-edit this block -->",
           f"- Input: `D3-layers.csv` sha256 `{hashlib.sha256(TAGS.read_bytes()).hexdigest()}`; "
           f"`LABELS-v1.csv` sha256 `{hashlib.sha256(LABELS.read_bytes()).hexdigest()}`", ""]
    pt = C.Counter(r["pattern"] for r in rows)
    assert [pt[p] for p in PATS] == [23, 23, 15, 33, 7, 2], pt
    xtab(rows, lambda r: r["pattern"], PATS, "All binding: layer x pattern", out)
    xtab(core, lambda r: r["pattern"], PATS, "Core (PSS != Y): layer x pattern", out)
    xtab(rows, lambda r: sev(r["severity"]), SEVS, "All binding: layer x auditor severity", out)
    xtab(core, lambda r: sev(r["severity"]), SEVS, "Core: layer x auditor severity", out)
    xtab(rows, lambda r: r["tier"], ["FULL", "LIGHT", "PSS"], "All binding: layer x tier", out)
    xtab(rows, lambda r: r["confidence"], ["high", "medium", "low"], "All binding: layer x confidence", out)
    hc = [r for r in core if r["confidence"] != "low"]
    xtab(hc, lambda r: r["pattern"], PATS, "Core, low-confidence tags removed: layer x pattern", out)
    # derived shares used in the paper sentences
    def share(rs, tags):
        return sum(r["layer_tag"] in tags for r in rs), len(rs)
    k, n = share(core, {"CONTRACT-ONLY"}); out.append(f"- Core decidable from the consumer contract alone: {k}/{n} ({100*k/n:.0f}%).")
    k, n = share(core, {"CIRCUIT-ONLY", "BOTH"}); out.append(f"- Core needing the circuit/statement (CIRCUIT-ONLY or BOTH): {k}/{n} ({100*k/n:.0f}%).")
    k, n = share(core, {"BOTH"}); out.append(f"- Core needing both sides compared: {k}/{n} ({100*k/n:.0f}%).")
    k, n = share(core, {"CONTRACT-ONLY", "BOTH"}); out.append(f"- Core needing the consumer contract at all (CONTRACT-ONLY or BOTH): {k}/{n} ({100*k/n:.0f}%).")
    k, n = share(core, {"VERIFIER/OFFCHAIN"}); out.append(f"- Core decided in verifier/off-chain code: {k}/{n} ({100*k/n:.0f}%).")
    alt = [dict(r, layer_tag=r["alt_tag_fix_side"]) for r in core]
    out.append("- Alternative reading (amendment A2 sensitivity: a CONTRACT-ONLY item whose report fix adds the value to the "
               "statement counts as BOTH): " + ", ".join(f"{L} {sum(r['layer_tag']==L for r in alt)}/{len(alt)} "
               f"({100*sum(r['layer_tag']==L for r in alt)/len(alt):.0f}%)" for L in LAYERS) + ".")
    out.append("")
    xtab(alt, lambda r: r["pattern"], PATS, "Core, alternative fix-side reading: layer x pattern", out)
    full = [r for r in rows if r["tier"] == "FULL"]
    out.append("- FULL tier: " + ", ".join(f"{L} {sum(r['layer_tag']==L for r in full)}" for L in LAYERS) + f" (n = {len(full)}).")
    out.append("")
    # stratified spot-check: allocate 15 proportionally with floor 3 per tag, seeded random within tag
    by = {L: sorted((r for r in rows if r["layer_tag"] == L), key=lambda r: int(r["item_id"][1:])) for L in LAYERS}
    alloc = {L: 3 for L in LAYERS}
    rest = NSPOT - sum(alloc.values())
    tot = sum(len(v) for v in by.values())
    extra = sorted(LAYERS, key=lambda L: -len(by[L]) / tot)
    for i in range(rest):
        alloc[extra[i % len(extra)]] += 1
    rng = random.Random(SEED)
    out += [f"### Author spot-check sample (15 items; seed {SEED}; floor 3 per tag, remainder to the largest tags)", "",
            "| item | tier | pattern | layer tag | conf. | rationale |", "|---|---|---|---|---|---|"]
    for L in LAYERS:
        for r in sorted(rng.sample(by[L], min(alloc[L], len(by[L]))), key=lambda r: int(r["item_id"][1:])):
            out.append(f"| {r['item_id']} | {r['tier']} | {r['pattern']} | {L} | {r['confidence']} | {r['rationale']} |")
    print("\n".join(out))


if __name__ == "__main__":
    main()

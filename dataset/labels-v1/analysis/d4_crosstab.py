#!/usr/bin/env python3
"""D4: cross-tabulate AI-proposed fix classes (D4-fixes.csv) by pattern and evaluate the
pre-specified signature-analogy test (D4-FIXES.md section 1.4).

Usage: python3 -I /home/pollmix/Coding/bc/BindCheck/dataset/labels-v1/analysis/d4_crosstab.py
Prints Markdown pasted into D4-FIXES.md. Stdlib only.
"""
import collections as C, csv, hashlib, math, pathlib

HERE = pathlib.Path(__file__).resolve().parents[1]
FIX = HERE / "D4-fixes.csv"
LABELS = HERE / "LABELS-v1.csv"
CLS = ["ADD-TO-STATEMENT", "CONTEXT-CHECK", "REPLAY-KEY", "PIN/CHECK-VERIFIER", "ENCODING", "OTHER/UNKNOWN"]
PATS = ["P1", "P2", "P3", "P4", "P5", "OTHER"]
STRICT = {"ADD-TO-STATEMENT", "CONTEXT-CHECK", "REPLAY-KEY"}
BROAD = STRICT | {"ENCODING", "PIN/CHECK-VERIFIER"}


def wilson(k, n, z=1.959964):
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return p, max(0.0, c - h), min(1.0, c + h)


def xtab(rows, title, out):
    t = C.Counter((r["fix_class"], r["pattern"]) for r in rows)
    out += [f"#### {title} (n = {len(rows)})", "", "| fix class | " + " | ".join(PATS) + " | total | % |", "|---" * (len(PATS) + 3) + "|"]
    for c in CLS:
        n = sum(t[(c, p)] for p in PATS)
        out.append(f"| {c} | " + " | ".join(str(t[(c, p)]) for p in PATS) + f" | {n} | {100 * n / len(rows):.0f}% |")
    out.append("| total | " + " | ".join(str(sum(t[(c, p)] for c in CLS)) for p in PATS) + f" | {len(rows)} | |")
    out.append("")


def analogy(rows, name, out):
    n = len(rows)
    ks = sum(r["fix_class"] in STRICT for r in rows)
    kb = sum(r["fix_class"] in BROAD for r in rows)
    ps, ls, hs = wilson(ks, n)
    pb, lb, hb = wilson(kb, n)
    if ps >= 0.5 and ls > 0.40:
        v = "supported"
    elif pb >= 0.5:
        v = "partly supported"
    else:
        v = "not supported"
    out.append(f"| {name} | {n} | {ks} ({ps:.2f} [{ls:.2f}, {hs:.2f}]) | {kb} ({pb:.2f} [{lb:.2f}, {hb:.2f}]) | {v} |")


def main():
    rows = list(csv.DictReader(open(FIX)))
    lab = {r["item_id"]: r for r in csv.DictReader(open(LABELS))}
    for r in rows:
        l = lab[r["item_id"]]
        assert l["binding"] == "Y" and not l["dup_of"] and l["pattern"] == r["pattern"] and l["proof_system_soundness"] == r["pss"]
        assert r["fix_class"] in CLS
    core = [r for r in rows if r["core"] == "Y"]
    assert len(rows) == 103 and len(core) == 87
    out = ["<!-- generated by analysis/d4_crosstab.py; do not hand-edit this block -->",
           f"- Input: `D4-fixes.csv` sha256 `{hashlib.sha256(FIX.read_bytes()).hexdigest()}`; "
           f"`LABELS-v1.csv` sha256 `{hashlib.sha256(LABELS.read_bytes()).hexdigest()}`", ""]
    xtab(rows, "All binding: fix class x pattern", out)
    xtab(core, "Core (PSS != Y): fix class x pattern", out)
    stated = [r for r in core if r["fix_evidence"] == "STATED"]
    xtab(stated, "Core, STATED fix evidence only", out)
    sub = C.Counter((r["fix_subtype"], r["core"]) for r in rows if r["fix_class"] == "OTHER/UNKNOWN")
    out.append("- OTHER/UNKNOWN subtypes (all / core): " + ", ".join(
        f"{s} {sub[(s,'Y')] + sub[(s,'N')]}/{sub[(s,'Y')]}" for s in sorted({k[0] for k in sub})) + ".")
    out.append("- Fix evidence (core): " + ", ".join(f"{k} {v}" for k, v in sorted(C.Counter(r["fix_evidence"] for r in core).items())) + ".")
    out.append("- Fix status (core): " + ", ".join(f"{k} {v}" for k, v in sorted(C.Counter(r["fix_status"] for r in core).items())) + ".")
    out.append("- Confidence (all): " + ", ".join(f"{k} {v}" for k, v in sorted(C.Counter(r["confidence"] for r in rows).items())) + ".")
    out += ["", "#### Signature-analogy test (pre-specified, section 1.4)", "",
            "| set | n | strict analogue: ADD+CONTEXT+REPLAY [Wilson 95%] | broad: + ENCODING + PIN/CHECK [Wilson 95%] | verdict |",
            "|---|---|---|---|---|"]
    analogy(core, "core 87", out)
    analogy(rows, "all 103", out)
    analogy(stated, "core, STATED only", out)
    analogy([r for r in core if r["confidence"] != "low"], "core, low-confidence removed", out)
    analogy([r for r in core if r["pattern"] in ("P1", "P2", "P3")], "core P1-P3 only", out)
    print("\n".join(out))


if __name__ == "__main__":
    main()

def clean(ax, axis="y"):
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)
    ax.grid(axis=axis, color=GRID, linewidth=0.6)
    ax.set_axisbelow(True)


def sev(s):  # identical to dataset/labels-v1/characterize.py
    s = s.lower()
    for k, v in (("crit", "Critical"), ("high", "High"), ("med", "Medium"), ("low", "Low/Info"),
                 ("info", "Low/Info"), ("warn", "Low/Info"), ("note", "Low/Info")):
        if k in s:
            return v
    return "Unrated"


# ---------------- Figure: study (pattern x severity; share of reports per year) ----------------
def fig_study():
  with plt.rc_context({"hatch.color": GREY}):
    _fig_study()


def _fig_study():
    rows = [r for r in csv.DictReader(open(LABELS)) if not r["dup_of"].strip() and r["binding"] != "U"]
    core = [r for r in rows if r["binding"] == "Y" and r["proof_system_soundness"] != "Y"]
    assert len(core) == 87, len(core)
    adj = [r for r in rows if r["binding"] == "Y" and r["proof_system_soundness"] == "Y"]
    pats = ["P1", "P2", "P3", "P4", "P5", "OTHER"]
    names = {"P1": "P1 effect", "P2": "P2 context", "P3": "P3 replay", "P4": "P4 verifier",
             "P5": "P5 interface", "OTHER": "other"}
    sevs = ["Critical", "High", "Medium", "Low/Info", "Unrated"]
    cols = {"Critical": "#7A1F1F", "High": ORANGE, "Medium": "#F0E442", "Low/Info": SKY, "Unrated": "#D9D9D9"}
    t = collections.Counter((r["pattern"], sev(r["severity"])) for r in core)

    fig, (a, b) = plt.subplots(1, 2, figsize=(7.0, 1.75), gridspec_kw={"width_ratios": [1.25, 1]})
    y = list(range(len(pats)))[::-1]
    for yi, p in zip(y, pats):
        x = 0
        for s in sevs:
            n = t[(p, s)]
            if n:
                a.barh(yi, n, left=x, color=cols[s], edgecolor="white", linewidth=0.8, height=0.66)
                if n >= 3:
                    a.text(x + n / 2, yi, str(n), ha="center", va="center", fontsize=6.5,
                           color="white" if s == "Critical" else INK)
                x += n
        if p == "P4":
            na = sum(1 for r in adj if r["pattern"] == "P4")
            a.barh(yi, na, left=x, color="white", edgecolor=GREY, hatch="....", linewidth=0.6, height=0.66)
            a.text(x + na + 0.4, yi, f"+{na} adjacent", va="center", fontsize=6.5, color=MUTE)
    a.set_yticks(y)
    a.set_yticklabels([names[p] for p in pats])
    a.set_xlabel("core binding findings (87)")
    a.legend(handles=[Patch(color=cols[s], label=s) for s in sevs], ncol=5, loc="lower center",
             bbox_to_anchor=(0.5, 1.0), handlelength=1.0, columnspacing=0.8)
    clean(a, "x")
    a.set_title("(a) pattern and auditor severity", fontsize=7.5, y=1.18)

    # D2-TREND core table (metric A, Wilson 95%): generated by dataset/labels-v1/analysis/d2_trend.py
    yrs = ["2021-22", "2023", "2024", "2025", "2026*"]
    n = [12, 60, 58, 94, 26]
    k = [3, 9, 9, 21, 4]
    lo = [0.09, 0.08, 0.08, 0.15, 0.06]
    hi = [0.53, 0.26, 0.27, 0.32, 0.34]
    sh = [kk / nn for kk, nn in zip(k, n)]
    xs = range(len(yrs))
    b.bar(xs, sh, color=BLUE, width=0.6)
    b.errorbar(xs, sh, yerr=[[s - l for s, l in zip(sh, lo)], [h - s for s, h in zip(sh, hi)]], fmt="none",
               ecolor=INK, elinewidth=0.6, capsize=1.8)
    for xi, kk, nn in zip(xs, k, n):
        b.text(xi, 0.005, f"{kk}/{nn}", ha="center", va="bottom", fontsize=6, color="white")
    b.set_xticks(list(xs))
    b.set_xticklabels(yrs)
    b.set_ylim(0, 0.56)
    b.set_ylabel("reports with $\\geq$1 core flaw")
    clean(b)
    b.set_title("(b) share of in-scope audit reports (Wilson 95%)", fontsize=7.5, y=1.18)
    fig.subplots_adjust(wspace=0.42)
    fig.savefig(os.path.join(HERE, "fig-study.pdf"))
    plt.close(fig)


# ---------------- Figure: held-out (projected) vs dev (measured) ----------------
def fig_heldout():
    # (label, positives, [(tool, value, projected?)])
    groups = [
        ("Dev-v4 (28)\nmean of 2 runs", 28, [("v2", 10.0, False), ("plain LLM", None, False), ("v4", 14.0, False)]),
        ("Fresh audited (14)\nmedian of 3", 14, [("v2", 4, True), ("plain LLM", 3, True), ("v4", 6, True)]),
        ("B3 mutants (37)\nmedian of 3", 37, [("v2", 21, True), ("plain LLM", 11, True), ("v4", 27, True)]),
        ("B3 proof side (11)\nmedian of 3", 11, [("v2", 3, True), ("plain LLM", 1, True), ("v4", 6, True)]),
    ]
    color = {"v2": SKY, "plain LLM": GREY, "v4": BLUE}
    fig, ax = plt.subplots(figsize=(COL, 1.85))
    w = 0.26
    for gi, (lab, pos, bars) in enumerate(groups):
        for bi, (tool, v, proj) in enumerate(bars):
            x = gi + (bi - 1) * w
            if v is None:
                ax.text(x, 0.02, "n/a", ha="center", va="bottom", fontsize=5.5, color=MUTE, rotation=90)
                continue
            r = v / pos
            if proj:
                ax.bar(x, r, w * 0.92, color=LIGHTRED if tool != "v4" else RED, edgecolor=RED,
                       hatch="////" if tool != "v4" else None, linewidth=0.5)
            else:
                ax.bar(x, r, w * 0.92, color=color[tool])
            ax.text(x, r + 0.015, f"{v:g}", ha="center", va="bottom", fontsize=5.8,
                    color=RED if proj else INK)
    ax.set_xticks(range(len(groups)))
    ax.set_xticklabels([g[0] for g in groups], fontsize=6.2)
    ax.set_ylabel("strict recall")
    ax.set_ylim(0, 1.0)
    clean(ax)
    ax.legend(handles=[Patch(color=SKY, label="v2"), Patch(color=GREY, label="plain LLM"),
                       Patch(color=BLUE, label="v4 (measured)"),
                       Patch(facecolor=LIGHTRED, edgecolor=RED, hatch="////", label="baseline (projected)"),
                       Patch(color=RED, label="v4 (projected)")],
              ncol=3, loc="upper center", bbox_to_anchor=(0.5, 1.28), handlelength=1.0, columnspacing=0.7)
    fig.savefig(os.path.join(HERE, "fig-heldout.pdf"))
    plt.close(fig)



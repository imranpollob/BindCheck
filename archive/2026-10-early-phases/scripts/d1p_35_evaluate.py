#!/usr/bin/env python3
"""Rerun the frozen D1P-34 target set and compare v1.2 warning identity."""

from __future__ import annotations

from datetime import datetime, timezone
import hashlib
import importlib.util
import json
from pathlib import Path
import sys


ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "results/raw/D1P-35/evaluation"
BASE_RAW = ROOT / "results/raw/D1P-34"


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def record(path: Path) -> dict:
    return {"path": str(path.resolve()), "bytes": path.stat().st_size, "sha256": sha256(path)}


def write_json(path: Path, value: object) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, indent=2, sort_keys=True) + "\n")


def load_runner():
    path = ROOT / "scripts/d1p_34_evaluate.py"
    spec = importlib.util.spec_from_file_location("d1p34_evaluator_for_d1p35", path)
    if spec is None or spec.loader is None:
        raise RuntimeError("cannot load D1P-34 evaluator")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    module.RAW = RAW
    module.ASTS = RAW / "compiler-asts"
    module.IRS = RAW / "consumer-relations"
    module.ANALYSES = RAW / "analyses"
    return module


def warning_identity(warning: dict) -> dict:
    return {
        "id": warning["id"],
        "rule": warning["rule"],
        "explanation": warning["explanation"],
        "suggested_fix": warning["suggested_fix"],
        "evidence": warning["evidence"],
        "target_identity": warning["target_identity"],
    }


def main() -> int:
    runner = load_runner()
    if runner.main() != 0:
        raise RuntimeError("D1P-34 evaluator returned nonzero")
    old_run = json.loads((BASE_RAW / "analysis-run.json").read_text())
    new_run = json.loads((RAW / "analysis-run.json").read_text())
    old_records = {item["target"]: item for item in old_run["targets"]}
    new_records = {item["target"]: item for item in new_run["targets"]}
    comparisons = []
    all_identity_equal = set(old_records) == set(new_records)
    only_locations_changed = True
    changed_locations = []
    for target in sorted(old_records):
        old_record = old_records[target]
        new_record = new_records[target]
        status_equal = old_record["status"] == new_record["status"]
        reason_equal = old_record.get("reason") == new_record.get("reason")
        old_analysis_path = BASE_RAW / f"analyses/{target}.json"
        new_analysis_path = RAW / f"analyses/{target}.json"
        if old_analysis_path.is_file() and new_analysis_path.is_file():
            old_analysis = json.loads(old_analysis_path.read_text())
            new_analysis = json.loads(new_analysis_path.read_text())
            old_identity = [warning_identity(item) for item in old_analysis["warnings"]]
            new_identity = [warning_identity(item) for item in new_analysis["warnings"]]
            identity_equal = old_identity == new_identity
            old_locations = [item["location"] for item in old_analysis["warnings"]]
            new_locations = [item["location"] for item in new_analysis["warnings"]]
            for warning_id, old_location, new_location in zip(
                    [item["id"] for item in old_analysis["warnings"]],
                    old_locations, new_locations):
                if old_location != new_location:
                    changed_locations.append({"target": target, "warning_id": warning_id,
                                              "from": old_location, "to": new_location})
            # Producer facts, warning count, and all consumer facts except the
            # reporting-only boundary location must remain equal.
            old_consumer = dict(old_analysis["consumer"])
            new_consumer = dict(new_analysis["consumer"])
            old_consumer.pop("verifier_location", None)
            new_consumer.pop("verifier_location", None)
            # The D1P-35 relation is regenerated byte-for-byte in a fresh raw
            # namespace, so only its path changes.
            old_consumer.pop("relation", None)
            new_consumer.pop("relation", None)
            nonlocation_equal = (
                old_analysis["producer"] == new_analysis["producer"]
                and old_consumer == new_consumer
                and old_analysis["warning_count"] == new_analysis["warning_count"]
                and old_analysis["rules"] == new_analysis["rules"]
                and old_analysis["polarity"] == new_analysis["polarity"]
                and old_analysis["limitations"] == new_analysis["limitations"]
            )
        else:
            identity_equal = old_analysis_path.is_file() == new_analysis_path.is_file()
            nonlocation_equal = identity_equal
            old_locations = []
            new_locations = []
        passed = status_equal and reason_equal and identity_equal and nonlocation_equal
        all_identity_equal &= passed
        only_locations_changed &= nonlocation_equal
        comparisons.append({
            "target": target,
            "status_equal": status_equal,
            "reason_equal": reason_equal,
            "warning_identity_equal": identity_equal,
            "nonlocation_analysis_equal": nonlocation_equal,
            "old_locations": old_locations,
            "new_locations": new_locations,
            "pass": passed,
        })

    adjudication = json.loads((BASE_RAW / "adjudication.json").read_text())
    totals = adjudication["totals"]
    result = {
        "schema": "bindcheck.d1p35.evaluation-comparison/v1",
        "generated_at_utc": datetime.now(timezone.utc).isoformat(),
        "baseline": record(BASE_RAW / "analysis-run.json"),
        "rerun": record(RAW / "analysis-run.json"),
        "target_count": len(comparisons),
        "all_status_reason_warning_identity_and_nonlocation_facts_equal": all_identity_equal,
        "only_reporting_locations_changed": only_locations_changed,
        "changed_locations": changed_locations,
        "unknown_warning_locations_before": sum(
            location.endswith(":?") for item in comparisons for location in item["old_locations"]
        ),
        "unknown_warning_locations_after": sum(
            location.endswith(":?") for item in comparisons for location in item["new_locations"]
        ),
        "payy_effect_locations_after": [
            item["to"] for item in changed_locations
            if item["target"].startswith("PY-") or item["target"] == "payy-earlier"
        ],
        "classification_counts_carried_by_identical_warnings": {
            "detected": totals["detected"],
            "unsupported": totals["unsupported"],
            "misses": totals["misses"],
        },
        "comparisons": comparisons,
    }
    output = RAW / "evaluation-comparison.json"
    write_json(output, result)
    print(json.dumps({
        "output": record(output),
        "identity_equal": all_identity_equal,
        "changed_location_count": len(changed_locations),
        "unknown_before": result["unknown_warning_locations_before"],
        "unknown_after": result["unknown_warning_locations_after"],
        "classification_counts": result["classification_counts_carried_by_identical_warnings"],
    }, indent=2))
    return 0 if all_identity_equal and result["unknown_warning_locations_after"] == 0 else 1


if __name__ == "__main__":
    raise SystemExit(main())

"""Predeclared synthetic labels for the passive verifier census."""

import unittest

from eval.verifier_census import classify_verifier


R = "21888242871839275222246405745257275088548364400416034343698204186575808495617"
Q = "21888242871839275222246405745257275088696311157297823662689037894645226208583"


def snarkjs(field: str, checks: str, arity: int = 2) -> str:
    return f'''// This file is generated with snarkJS.
pragma solidity >=0.7.0 <0.9.0;
contract Verifier {{
  uint256 constant r = {R};
  uint256 constant q = {Q};
  function verifyProof(uint[2] calldata _pA, uint[{arity}] calldata _pubSignals) public view returns (bool) {{
    assembly {{
      function checkField(v) {{ if iszero(lt(v, {field})) {{ return(0, 0x20) }} }}
      {checks}
      let ok := staticcall(gas(), 8, 0, 0, 0, 0)
      mstore(0, ok)
      return(0, 0x20)
    }}
  }}
}}
'''


class VerifierCensusTests(unittest.TestCase):
    def one(self, source: str) -> dict:
        rows = classify_verifier(source)
        self.assertEqual(len(rows), 1)
        return rows[0]

    def test_snarkjs_current_scalar_all_positions(self) -> None:
        item = self.one(snarkjs("r", "checkField(calldataload(add(_pubSignals, 0)))\ncheckField(calldataload(add(_pubSignals, 32)))"))
        self.assertEqual(item["generator"], "SNARKJS_CURRENT_STYLE")
        self.assertEqual(item["range_class"], "R_ALL")
        self.assertEqual(item["guarded_positions"], [0, 1])
        self.assertEqual(item["behavior"], "PAIRING_VERIFIER")

    def test_wrong_base_field_is_not_scalar_guard(self) -> None:
        item = self.one(snarkjs("q", "checkField(calldataload(add(_pubSignals, 0)))\ncheckField(calldataload(add(_pubSignals, 32)))"))
        self.assertEqual(item["range_class"], "Q_ALL")
        self.assertEqual(item["guarded_positions"], [0, 1])

    def test_partial_and_absent_guards(self) -> None:
        partial = self.one(snarkjs("r", "checkField(calldataload(add(_pubSignals, 0)))"))
        absent = self.one(snarkjs("r", ""))
        self.assertEqual(partial["range_class"], "R_PARTIAL")
        self.assertEqual(partial["guarded_positions"], [0])
        self.assertEqual(absent["range_class"], "NONE")

    def test_legacy_snarkjs_template(self) -> None:
        source = '''// This file is generated with snarkJS.
library Pairing { function pairingProd4() internal view returns (bool) { return true; } }
contract Verifier {
  function verifyProof(uint[2] memory a, uint[1] memory input) public view returns (bool) {
    return Pairing.pairingProd4();
  }
}'''
        item = self.one(source)
        self.assertEqual(item["generator"], "SNARKJS_LEGACY_STYLE")
        self.assertEqual(item["range_class"], "NONE")
        self.assertEqual(item["behavior"], "PAIRING_VERIFIER")

    def test_gnark_signature(self) -> None:
        item = self.one('''// Code generated by gnark. DO NOT EDIT.
contract Verifier { function verifyProof(uint256[1] calldata input) public view returns (bool) {
  bool ok = pair(input[0]); return ok;
} function pair(uint256 x) internal view returns (bool) { return x == 1; } }''')
        self.assertEqual(item["generator"], "GNARK")

    def test_unconditional_accept_and_reject(self) -> None:
        yes = self.one('contract MockVerifier { function verifyProof(uint[] memory input) public pure returns (bool) { return true; } }')
        no = self.one('contract StubVerifier { function verifyProof(uint[] memory input) public pure returns (bool) { return false; } }')
        self.assertEqual(yes["behavior"], "ACCEPT_ALL")
        self.assertEqual(no["behavior"], "REJECT_ALL")
        self.assertEqual(yes["range_class"], "NONE")

    def test_simplified_and_dummy_key(self) -> None:
        simplified = self.one('contract Verifier { // simplified verification\nfunction verifyProof(uint[] calldata input) public pure returns (bool) { return input.length > 0; } }')
        dummy = self.one('contract Verifier { uint256 constant vkx = 0x1234;\nfunction verifyProof(uint[] calldata input) public view returns (bool) { return Pairing.pairingProd4(); } }')
        self.assertEqual(simplified["behavior"], "SIMPLIFIED")
        self.assertEqual(dummy["behavior"], "DUMMY_CONSTANTS")

    def test_comment_only_return_true_does_not_make_accept_all(self) -> None:
        source = snarkjs("r", "checkField(calldataload(add(_pubSignals, 0)))\ncheckField(calldataload(add(_pubSignals, 32)))")
        source = source.replace("pragma", "// return true;\npragma", 1)
        self.assertEqual(self.one(source)["behavior"], "PAIRING_VERIFIER")

    def test_unknown_helper_guard_is_not_inferred(self) -> None:
        item = self.one('contract Verifier { function verifyProof(uint[1] calldata input) public view returns (bool) { check(input[0]); return pairing(input); } }')
        self.assertEqual(item["range_class"], "UNKNOWN")


if __name__ == "__main__":
    unittest.main()
